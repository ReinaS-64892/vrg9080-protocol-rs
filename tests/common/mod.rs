pub fn status(mask: u8) -> [u8; 64] {
    let mut report = [0; 64];
    report[..9].copy_from_slice(&[0, 1, 0x0b, 9, mask, 1, 30, 31, 2]);
    checksum(&mut report);
    report
}

pub fn response(command: u8, status: u8, data: &[u8]) -> [u8; 64] {
    let mut report = [0; 64];
    let length = 5 + data.len();
    report[..4].copy_from_slice(&[0xaa, 0x11, command, length as u8]);
    report[4..length - 1].copy_from_slice(data);
    report[length - 1] = status;
    checksum(&mut report);
    report
}
