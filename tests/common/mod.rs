#![allow(dead_code)]

pub fn checksum(report: &mut [u8; 64]) {
    let length = usize::from(report[3]);
    report[length] = report[..length]
        .iter()
        .fold(0_u8, |sum, byte| sum.wrapping_add(*byte));
}

